_cache: dict[tuple[str, int, tuple[int, int, int]], pygame.Surface] = {}


def _render_uncached(text: str, scale: int, color: tuple[int, int, int]) -> pygame.Surface:
    n = len(text)
    width = max(n * GLYPH_W * scale + max(n - 1, 0) * SPACING * scale, 1)
    height = GLYPH_H * scale
    surf = pygame.Surface((width, height), pygame.SRCALPHA)

    x = 0
    for ch in text:
        glyph = GLYPHS.get(ch, _BLANK)
        for row, line in enumerate(glyph):
            for col, px in enumerate(line):
                if px == "#":
                    surf.fill(color, (x + col * scale, row * scale, scale, scale))
        x += (GLYPH_W + SPACING) * scale

    return surf


def render(text: str, scale: int, color: tuple[int, int, int]) -> pygame.Surface:
    """Renderiza texto (maiusculas) na fonte bitmap 5x7, com cache por (texto, escala, cor)."""
    text = text.upper()
    key = (text, scale, color)
    cached = _cache.get(key)
    if cached is None:
        cached = _render_uncached(text, scale, color)
        _cache[key] = cached
    return cached
